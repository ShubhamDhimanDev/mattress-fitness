#!/usr/bin/env node
// Creates storefront/.env.demo: the environment file that connects the storefront to a demo store with NO third-party
// services. Nothing for Extend, Klaviyo, GA4, Meta, Affirm, maps or reviews is written, so every one of them stays off
// (docs/deployment/DEMO_STORE_SETUP.md). Zero dependencies, so it runs before `npm install`.
//
//   node scripts/setup/demo-env.mjs --mock
//   node scripts/setup/demo-env.mjs --store my-demo.myshopify.com --token <32-character public Storefront API token>
//
// Options: --no-offers (writes OFFERS_ENABLED=false), --out .env.demo (a file name like .env.<name> inside storefront/),
// --force (overwrite an existing file), --help. The two cookie secrets are generated here with the platform's random
// source and are never printed. The public Storefront token is public by design (PUBLIC_ prefix), but this tool still
// does not echo it. Exit codes: 0 written, 1 the file already exists, 2 usage error.

import {randomBytes} from 'node:crypto';
import {existsSync, writeFileSync, mkdirSync} from 'node:fs';
import {dirname, join, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {parseArgs} from 'node:util';

const MOCK_DOMAIN = 'bedding.mock.shop';
// bedding.mock.shop does not check the token, but Hydrogen's consent code logs an error unless it is exactly 32 characters.
const MOCK_TOKEN = '0'.repeat(32);
const SHOP_DOMAIN = /^[a-z0-9][a-z0-9-]{0,60}\.myshopify\.com$/;
const TOKEN = /^[A-Za-z0-9]{32}$/;
const OUT_NAME = /^\.env\.[A-Za-z0-9_-]{1,40}$/;

const USAGE = `Usage:
  node scripts/setup/demo-env.mjs --mock
  node scripts/setup/demo-env.mjs --store <shop>.myshopify.com --token <32-character public Storefront API token>

Options:
  --no-offers     also write OFFERS_ENABLED=false (the offers engine stays off)
  --out <name>    file name inside storefront/, like .env.demo (the default)
  --force         overwrite an existing file
  --help          this text`;

export class UsageError extends Error {}

/** Parses and validates the command line. Pure, so it is unit tested. */
export function parseOptions(argv) {
  let parsed;
  try {
    parsed = parseArgs({
      args: argv,
      options: {
        mock: {type: 'boolean', default: false},
        store: {type: 'string'},
        token: {type: 'string'},
        'no-offers': {type: 'boolean', default: false},
        out: {type: 'string', default: '.env.demo'},
        force: {type: 'boolean', default: false},
        help: {type: 'boolean', default: false},
      },
      allowPositionals: false,
    }).values;
  } catch (error) {
    throw new UsageError(error instanceof Error ? error.message : 'bad usage');
  }
  if (parsed.help) return {help: true};
  if (parsed.mock === (parsed.store !== undefined)) {
    throw new UsageError('Give exactly one of --mock or --store.');
  }
  if (!OUT_NAME.test(parsed.out)) {
    throw new UsageError(
      '--out must be a file name like .env.demo (letters, digits, _ and -), inside storefront/.',
    );
  }
  if (parsed.mock) {
    if (parsed.token !== undefined) {
      throw new UsageError('--token is not used with --mock.');
    }
    return {
      help: false,
      domain: MOCK_DOMAIN,
      token: MOCK_TOKEN,
      out: parsed.out,
      noOffers: parsed['no-offers'],
      force: parsed.force,
    };
  }
  const domain = (parsed.store ?? '').toLowerCase();
  if (!SHOP_DOMAIN.test(domain)) {
    throw new UsageError('--store must look like my-demo.myshopify.com.');
  }
  if (parsed.token === undefined || !TOKEN.test(parsed.token)) {
    throw new UsageError(
      '--token must be the 32-character public Storefront API token (letters and digits only).',
    );
  }
  return {
    help: false,
    domain,
    token: parsed.token,
    out: parsed.out,
    noOffers: parsed['no-offers'],
    force: parsed.force,
  };
}

/** A 64-character hex secret from the platform's random source. */
export function newSecret(bytes = randomBytes) {
  return bytes(32).toString('hex');
}

/** The file content. Only the variables a demo needs; nothing for any third-party service. */
export function buildEnvFile(options, secrets) {
  const lines = [
    '# Demo store connection with NO third-party services. Generated by scripts/setup/demo-env.mjs.',
    '# Git ignores .env.* files. Never commit this file or paste it anywhere.',
    '# Extend, Klaviyo, GA4, Meta, Affirm, maps and Judge.me are intentionally not set: each stays off.',
    '',
    `PUBLIC_STORE_DOMAIN=${options.domain}`,
    `PUBLIC_CHECKOUT_DOMAIN=${options.domain}`,
    `PUBLIC_STOREFRONT_API_TOKEN=${options.token}`,
    `SESSION_SECRET=${secrets.session}`,
    `DELIVERY_COOKIE_SECRET=${secrets.delivery}`,
  ];
  if (options.noOffers) {
    lines.push('', '# No offers: the cart goes straight to checkout.');
    lines.push('OFFERS_ENABLED=false');
  }
  return `${lines.join('\n')}\n`;
}

export function run(argv, {storefrontDir, out = console.log, bytes} = {}) {
  let options;
  try {
    options = parseOptions(argv);
  } catch (error) {
    if (error instanceof UsageError) {
      out(`${error.message}\n\n${USAGE}`);
      return 2;
    }
    throw error;
  }
  if (options.help) {
    out(USAGE);
    return 0;
  }
  const target = resolve(join(storefrontDir, options.out));
  if (existsSync(target) && !options.force) {
    out(`${options.out} already exists. Nothing was changed. Use --force to replace it.`);
    return 1;
  }
  mkdirSync(dirname(target), {recursive: true});
  const secrets = {session: newSecret(bytes), delivery: newSecret(bytes)};
  writeFileSync(target, buildEnvFile(options, secrets), {mode: 0o600});
  out(
    [
      `Wrote storefront/${options.out} for ${options.domain}.`,
      'Variables written (values are not shown): PUBLIC_STORE_DOMAIN, PUBLIC_CHECKOUT_DOMAIN, PUBLIC_STOREFRONT_API_TOKEN, SESSION_SECRET, DELIVERY_COOKIE_SECRET' +
        (options.noOffers ? ', OFFERS_ENABLED' : '') +
        '.',
      'Third-party services: none configured (Extend, Klaviyo, GA4, Meta, Affirm, maps, Judge.me stay off).',
      '',
      'Next, from storefront/:',
      `  npm install`,
      `  npm run dev -- --port 3400 --env-file ${options.out}`,
      'Then open http://localhost:3400',
    ].join('\n'),
  );
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const here = dirname(fileURLToPath(import.meta.url));
  process.exitCode = run(process.argv.slice(2), {
    storefrontDir: resolve(here, '..', '..', 'storefront'),
  });
}
